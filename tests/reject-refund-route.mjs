import assert from 'node:assert/strict';
import {env,state,sqlite,route,seed,call,row,complete,contract} from './route-harness.mjs';
seed('refund-path');env.CHAIN_WRITES_ENABLED='testnet-approved';
sqlite.prepare("UPDATE bounties SET status='submitted', funding_stage='funded', contract_address=?, onchain_job_id='2' WHERE id='refund-path'").run(contract);
const settle=await route('app/api/bounties/[id]/settle/route.ts');
assert.equal((await call(settle,'refund-path','POST',{action:'reject'},'B')).status,403);
assert.equal((await call(settle,'refund-path','POST',{action:'refund'},'A')).status,409);
assert.equal(state.sends,0);
assert.equal((await call(settle,'refund-path','POST',{action:'reject',note:'Test rejection'},'A')).status,202);
assert.equal((await call(settle,'refund-path','POST',{action:'reject'},'A')).status,409);
assert.equal(state.sends,1);
complete('refund-path',false);
assert.equal((await call(settle,'refund-path','POST',{action:'reconcile'},'A')).status,200);
assert.equal(row('refund-path').status,'rejected');
assert.equal((await call(settle,'refund-path','POST',{action:'approve'},'A')).status,409);
assert.equal((await call(settle,'refund-path','POST',{action:'refund'},'B')).status,403);
assert.equal((await call(settle,'refund-path','POST',{action:'refund'},'A')).status,202);
complete('refund-path',false);
assert.equal((await call(settle,'refund-path','POST',{action:'reconcile'},'A')).status,200);
assert.equal(row('refund-path').status,'expired');
assert.equal((await call(settle,'refund-path','POST',{action:'refund'},'A')).status,409);
assert.equal(state.sends,2);
console.log('PASS reject/refund: client-only / premature refund blocked / receipt transitions / approve after reject blocked / duplicate refund blocked (mock only)');sqlite.close();
