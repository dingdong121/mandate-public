const settle=await route('app/api/bounties/[id]/settle/route.ts');
assert.equal((await call(settle,'delivery','POST',{action:'submit',deliverable},'A')).status,403);
assert.equal((await call(settle,'delivery','POST',{action:'submit',deliverable:'Changed delivery evidence'},'B')).status,409);
assert.equal(state.sends,0);
env.CHAIN_WRITES_ENABLED=undefined;
assert.equal((await call(settle,'delivery','POST',{action:'submit',deliverable},'B')).status,423);
assert.equal(state.sends,0);
env.CHAIN_WRITES_ENABLED='testnet-approved';
assert.equal((await call(settle,'delivery','POST',{action:'submit',deliverable},'B')).status,202);
assert.equal(state.sends,1);
