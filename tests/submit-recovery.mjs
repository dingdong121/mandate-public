import assert from 'node:assert/strict';
import {env,state,sqlite,route,seed,call,row,contract} from './route-harness.mjs';
seed('delivery');
env.CHAIN_WRITES_ENABLED='testnet-approved';
sqlite.prepare("UPDATE bounties SET status='funded', funding_stage='funded', contract_address=?, onchain_job_id='1' WHERE id='delivery'").run(contract);
const deliverable='Original delivery evidence';
const deliveryHash='0x'+Buffer.from(await crypto.subtle.digest('SHA-256',new TextEncoder().encode(deliverable))).toString('hex');
const payload={resource:'bounty:delivery',action:'submit_pending',payload:{walletId:'agent-wallet',target:contract,signature:'submit(uint256,bytes32,bytes)',parameters:['1',deliveryHash,'0x']}};
const hash=Buffer.from(await crypto.subtle.digest('SHA-256',new TextEncoder().encode(JSON.stringify(payload)))).toString('hex');
