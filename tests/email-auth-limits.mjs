import fs from 'node:fs';
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
const db=new DatabaseSync(':memory:');
db.exec(fs.readFileSync('deployment/email-auth-schema.sql','utf8'));
const insert=db.prepare('INSERT INTO email_login_challenges(id,email,digest,created_at,day,expires_at,delivered) VALUES (?,?,?,?,?,?,1)');
insert.run('first','one@example.com','correct',100,'day1',1000);
assert.throws(()=>insert.run('early','one@example.com','correct',159,'day1',1000),/email_send_cooldown/);
insert.run('later','one@example.com','correct',160,'day1',1000);
for(let i=2;i<80;i++)insert.run(`id${i}`,`user${i}@example.com`,'correct',160,'day1',1000);
assert.throws(()=>insert.run('over','new@example.com','correct',160,'day1',1000),/email_daily_limit/);
assert.equal(db.prepare('SELECT count(*) AS n FROM email_login_challenges').get().n,80);
insert.run('next-day','new@example.com','correct',200,'day2',1000);
const consume=db.prepare('UPDATE email_login_challenges SET attempts=attempts+1,consumed=CASE WHEN digest=? THEN 1 ELSE 0 END WHERE id=? AND consumed=0 AND delivered=1 AND expires_at>? AND attempts<5 RETURNING consumed');
assert.equal(consume.get('wrong','first',201).consumed,0);
assert.equal(consume.get('correct','first',201).consumed,1);
assert.equal(consume.get('correct','first',201),undefined);
for(let i=0;i<5;i++)assert.equal(consume.get('wrong','later',201).consumed,0);
assert.equal(consume.get('correct','later',201),undefined);
assert.equal(consume.get('correct','next-day',1000),undefined);
db.close();
console.log('PASS SQL limits: 60-second boundary, 80/day cap, next day, one-time consumption, five attempts, expiry. Local SQLite only, not live D1 concurrency.');
